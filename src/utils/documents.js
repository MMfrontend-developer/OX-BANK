/**
 * documents.js — printable transaction receipts and account statements.
 * Opens a self-contained HTML document in a new window and triggers print
 * (the browser's "Save as PDF" gives the customer a PDF).
 */
import { formatCurrency } from './currency.js';

const esc = (v) =>
  String(v ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

const fmtDate = (iso) =>
  new Date(iso).toLocaleString(undefined, { day: '2-digit', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit' });

const BASE_CSS = `
  *{box-sizing:border-box;margin:0;padding:0}
  body{font-family:Inter,system-ui,-apple-system,sans-serif;color:#1a202c;background:#fff;padding:32px;font-size:13px;line-height:1.5}
  .brand{display:flex;justify-content:space-between;align-items:flex-start;border-bottom:3px solid #551A8B;padding-bottom:16px;margin-bottom:20px}
  .brand h1{font-size:22px;color:#551A8B;letter-spacing:-.02em}
  .brand p{color:#4a5568;font-size:12px}
  .muted{color:#4a5568}
  table{width:100%;border-collapse:collapse}
  th,td{text-align:left;padding:8px 6px;border-bottom:1px solid #e2e8f0;vertical-align:top}
  th{font-size:11px;text-transform:uppercase;letter-spacing:.04em;color:#4a5568;background:#f7f7fb}
  .num{text-align:right;font-variant-numeric:tabular-nums;white-space:nowrap}
  .credit{color:#006300}
  .footer{margin-top:28px;font-size:11px;color:#718096;border-top:1px solid #e2e8f0;padding-top:12px}
  .demo{display:inline-block;margin-top:6px;padding:2px 8px;border:1px solid #ff6600;color:#c2410c;border-radius:999px;font-size:11px;font-weight:600}
  @media print{body{padding:0}.noprint{display:none}}
`;

function openPrintable(title, bodyHtml) {
  const win = window.open('', '_blank', 'width=900,height=1000');
  if (!win) return false;
  win.document.open();
  win.document.write(`<!doctype html><html><head><meta charset="utf-8"><title>${esc(title)}</title><style>${BASE_CSS}</style></head><body>${bodyHtml}
    <p class="noprint" style="margin-top:24px"><button onclick="window.print()" style="padding:10px 18px;border-radius:8px;border:0;background:#551A8B;color:#fff;font-weight:600;cursor:pointer">Print / Save as PDF</button></p>
    <script>window.addEventListener('load',function(){setTimeout(function(){window.print()},300)})</script></body></html>`);
  win.document.close();
  return true;
}

const header = (title, subtitle) => `
  <div class="brand">
    <div><h1>OXBANK</h1><p>Digital Banking · Lagos, Nigeria</p><span class="demo">Demo document — not a real bank record</span></div>
    <div style="text-align:right"><strong style="font-size:15px">${esc(title)}</strong><p>${esc(subtitle)}</p></div>
  </div>`;

/**
 * Print a receipt for one ledger entry.
 * @param {Object} tx — ledger entry (+ optional accountNumber/accountType)
 * @param {Object} user — { name }
 */
export function printReceipt(tx, user) {
  const rows = [
    ['Status', 'Successful'],
    ['Amount', `${tx.type === 'credit' ? '+' : '−'}${formatCurrency(tx.amount)}`],
    ['Type', tx.type === 'credit' ? 'Credit' : 'Debit'],
    ['Description', tx.note || tx.category],
    ['Category', tx.category],
    ['Account', `${user?.name || ''} · ${tx.accountType || ''} ${tx.accountNumber || ''}`],
    tx.counterpartName ? [tx.type === 'credit' ? 'From' : 'To', `${tx.counterpartName}${tx.counterpartAccount ? ` · ${tx.counterpartAccount}` : ''}`] : null,
    ['Balance after', formatCurrency(tx.balanceAfter)],
    ['Date', fmtDate(tx.createdAt)],
    ['Reference', tx.reference],
  ].filter(Boolean);

  const body = `${header('Transaction Receipt', fmtDate(tx.createdAt))}
    <table>${rows.map(([k, v]) => `<tr><th style="width:35%">${esc(k)}</th><td>${esc(v)}</td></tr>`).join('')}</table>
    <p class="footer">This receipt was generated by OXBANK (demo). Keep the reference number for any enquiry.</p>`;
  return openPrintable(`Receipt ${tx.reference}`, body);
}

/**
 * Print an account statement for [from, to].
 * @param {{user:Object, account:Object, entries:Object[], from:Date, to:Date}} p
 */
export function printStatement({ user, account, entries, from, to }) {
  const inRange = entries
    .filter((e) => {
      const t = new Date(e.createdAt);
      return t >= from && t <= to;
    })
    .sort((a, b) => new Date(a.createdAt) - new Date(b.createdAt));

  const credits = inRange.filter((e) => e.type === 'credit').reduce((s, e) => s + e.amount, 0);
  const debits = inRange.filter((e) => e.type === 'debit').reduce((s, e) => s + e.amount, 0);
  const first = inRange[0];
  const opening = first ? first.balanceAfter + (first.type === 'credit' ? -first.amount : first.amount) : null;
  const closing = inRange.length ? inRange[inRange.length - 1].balanceAfter : null;
  const range = `${from.toLocaleDateString()} – ${to.toLocaleDateString()}`;

  const summary = [
    ['Account holder', user?.name],
    ['Account', `${account.type} · ${account.number}`],
    ['Period', range],
    ['Opening balance', opening === null ? '—' : formatCurrency(opening)],
    ['Total credits', formatCurrency(credits)],
    ['Total debits', formatCurrency(debits)],
    ['Closing balance', closing === null ? formatCurrency(account.balance) : formatCurrency(closing)],
  ];

  const body = `${header('Account Statement', range)}
    <table style="margin-bottom:20px">${summary.map(([k, v]) => `<tr><th style="width:35%">${esc(k)}</th><td>${esc(v)}</td></tr>`).join('')}</table>
    <table>
      <thead><tr><th>Date</th><th>Description</th><th>Reference</th><th class="num">Debit</th><th class="num">Credit</th><th class="num">Balance</th></tr></thead>
      <tbody>${
        inRange.length
          ? inRange
              .map(
                (e) => `<tr><td>${esc(new Date(e.createdAt).toLocaleDateString())}</td><td>${esc(e.note || e.category)}</td><td class="muted">${esc(e.reference)}</td>
                <td class="num">${e.type === 'debit' ? esc(formatCurrency(e.amount)) : ''}</td>
                <td class="num credit">${e.type === 'credit' ? esc(formatCurrency(e.amount)) : ''}</td>
                <td class="num">${esc(formatCurrency(e.balanceAfter))}</td></tr>`,
              )
              .join('')
          : '<tr><td colspan="6" class="muted">No transactions in this period.</td></tr>'
      }</tbody>
    </table>
    <p class="footer">Generated ${esc(fmtDate(new Date().toISOString()))}. Demo statement — all values are simulated.</p>`;
  return openPrintable(`Statement ${account.number}`, body);
}

/** Download rows as a CSV file. */
export function downloadCSV(filename, headers, rows) {
  const cell = (v) => {
    const s = String(v ?? '');
    return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
  };
  const csv = [headers, ...rows].map((r) => r.map(cell).join(',')).join('\n');
  const blob = new Blob([`\uFEFF${csv}`], { type: 'text/csv;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
